-- =============================================
-- PHẦN 1: CẤU HÌNH CƠ BẢN & CÁC BẢNG DANH MỤC
-- =============================================

-- 1. Bảng Chi nhánh (Kho hàng)
CREATE TABLE stores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL, -- VD: Kho Tổng, Cửa hàng Q1
    address TEXT,
    phone TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Bảng Danh mục Sản phẩm (Hỗ trợ danh mục cha/con)
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT UNIQUE NOT NULL, -- URL thân thiện
    parent_id BIGINT REFERENCES categories(id) ON DELETE SET NULL, -- Danh mục cha
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Bảng Nhà cung cấp
CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    address TEXT, -- JSON hoặc Text
    phone TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);


-- =============================================
-- PHẦN 2: SẢN PHẨM & BIẾN THỂ
-- =============================================

-- 4. Bảng Sản phẩm (Thông tin chung)
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    description TEXT,
    base_price DECIMAL(12,0) NOT NULL, -- Giá niêm yết cơ bản
    images TEXT[], -- Mảng link ảnh
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. Bảng Trung gian: Sản phẩm - Danh mục (Một áo thuộc nhiều danh mục)
CREATE TABLE product_categories (
    product_id BIGINT REFERENCES products(id) ON DELETE CASCADE,
    category_id BIGINT REFERENCES categories(id) ON DELETE CASCADE,
    PRIMARY KEY (product_id, category_id)
);

-- 6. Bảng Biến thể (SKU) - Chi tiết từng size/màu
CREATE TABLE variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES products(id) ON DELETE CASCADE,
    sku TEXT UNIQUE NOT NULL, -- Mã vạch (Barcode)
    size TEXT NOT NULL,
    color TEXT NOT NULL,
    current_price DECIMAL(12,0), -- Nếu null thì lấy base_price của products
    image_url TEXT, -- Ảnh riêng cho biến thể màu này (nếu có)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- =============================================
-- PHẦN 3: KHO HÀNG FIFO (TRÁI TIM CỦA HỆ THỐNG)
-- =============================================

-- 7. Bảng Phiếu Nhập kho
CREATE TABLE purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT REFERENCES suppliers(id),
    store_id BIGINT REFERENCES stores(id),
    total_cost DECIMAL(12,0) NOT NULL DEFAULT 0,
    note TEXT,
    purchase_date TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 8. Bảng Chi tiết nhập kho
CREATE TABLE purchase_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT REFERENCES purchase_orders(id) ON DELETE CASCADE,
    variant_id BIGINT REFERENCES variants(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_cost DECIMAL(12,0) NOT NULL -- Giá vốn lúc nhập
);

-- 9. Bảng Lô hàng tồn kho (Inventory Batches) - Dùng để tính FIFO
-- Mỗi lần nhập hàng sẽ tạo ra một "Batch" mới tại đây. Khi bán sẽ trừ dần batch cũ nhất.
CREATE TABLE inventory_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT REFERENCES stores(id),
    variant_id BIGINT REFERENCES variants(id),
    purchase_item_id BIGINT REFERENCES purchase_items(id), -- Link tới phiếu nhập gốc
    original_quantity INTEGER NOT NULL, -- Số lượng ban đầu
    quantity_remaining INTEGER NOT NULL CHECK (quantity_remaining >= 0), -- Số còn lại
    cost_price DECIMAL(12,0) NOT NULL, -- Giá vốn lô này
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() -- Quan trọng để sort FIFO
);

-- 1. Thêm cột tên lô hàng (để lưu mã PO-...)
ALTER TABLE inventory_batches 
ADD COLUMN batch_name TEXT;

-- 2. Thêm cột nhà cung cấp (để biết lô này nhập của ai)
ALTER TABLE inventory_batches 
ADD COLUMN supplier_id BIGINT REFERENCES suppliers(id);

-- Index để tìm kiếm tồn kho nhanh hơn
CREATE INDEX idx_inventory_fifo ON inventory_batches (store_id, variant_id, created_at ASC);

-- =============================================
-- PHẦN 4: KHÁCH HÀNG & KHUYẾN MÃI
-- =============================================

-- 10. Bảng Khách hàng
CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID, -- Link tới Supabase Auth (NULL nếu là khách vãng lai)
    full_name TEXT NOT NULL,
    phone TEXT,
    email TEXT,
    address TEXT,
    loyalty_points INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
-- Index số điện thoại để tra cứu nhanh khách vãng lai
CREATE INDEX idx_customer_phone ON customers (phone);

-- 11. Bảng Khuyến mãi (Voucher)
CREATE TABLE promotions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    description TEXT,
    discount_type TEXT CHECK (discount_type IN ('percent', 'fixed')), -- % hoặc trừ tiền thẳng
    discount_value DECIMAL(12,0) NOT NULL,
    min_order_value DECIMAL(12,0) DEFAULT 0,
    start_date TIMESTAMP WITH TIME ZONE,
    end_date TIMESTAMP WITH TIME ZONE,
    requires_account BOOLEAN DEFAULT TRUE, -- True: Phải đăng nhập mới dùng đc
    is_active BOOLEAN DEFAULT TRUE
);

-- 12. Bảng Giỏ hàng (Chỉ dành cho khách đã đăng nhập)
CREATE TABLE carts (
    user_id UUID PRIMARY KEY, -- Một user chỉ có 1 giỏ hàng active
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id UUID REFERENCES carts(user_id) ON DELETE CASCADE,
    variant_id BIGINT REFERENCES variants(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0)
);

-- =============================================
-- PHẦN 5: BÁN HÀNG (SALES)
-- =============================================

-- 13. Bảng Đơn hàng
CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL, -- Mã đơn hàng (VD: ORD-2025-001)
    customer_id BIGINT REFERENCES customers(id),
    store_id BIGINT REFERENCES stores(id), -- Đơn này thuộc kho nào
    promotion_id BIGINT REFERENCES promotions(id),
    
    -- Các cột tiền
    subtotal DECIMAL(12,0) NOT NULL, -- Tiền hàng
    discount_amount DECIMAL(12,0) DEFAULT 0, -- Tiền giảm giá
    shipping_fee DECIMAL(12,0) DEFAULT 0, -- Phí ship
    total_amount DECIMAL(12,0) NOT NULL, -- Khách phải trả (Sub - Disc + Ship)
    
    payment_method TEXT DEFAULT 'cod', -- cod, banking
    status TEXT DEFAULT 'pending', -- pending, confirmed, shipping, completed, cancelled, returned
    note TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 1. Thêm cột lưu thông tin người nhận (quan trọng cho đơn hàng vãng lai)
ALTER TABLE orders
