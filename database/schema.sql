-- 2. Cho phép store_id null (vì mua online chưa chắc đã assign ngay cho kho nào)
ALTER TABLE orders 
ALTER COLUMN store_id DROP NOT NULL;

-- 14. Bảng Chi tiết đơn hàng
CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES orders(id) ON DELETE CASCADE,
    variant_id BIGINT REFERENCES variants(id),
    quantity INTEGER NOT NULL,
    price_at_purchase DECIMAL(12,0) NOT NULL, -- Giá bán cho khách lúc đó
    cogs_total DECIMAL(12,0) DEFAULT 0 -- Tổng giá vốn của dòng này (Tính bằng FIFO logic sau khi bán)
);

-- =============================================
-- PHẦN 6: TÀI CHÍNH (FINANCE)
-- =============================================

-- 15. Danh mục chi phí
CREATE TABLE expense_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL, -- Quảng cáo, Thuê mặt bằng, Lương...
    description TEXT
);

-- 16. Phiếu chi
CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT REFERENCES stores(id),
    category_id BIGINT REFERENCES expense_categories(id),
    amount DECIMAL(12,0) NOT NULL,
    expense_date DATE DEFAULT CURRENT_DATE,
    note TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

